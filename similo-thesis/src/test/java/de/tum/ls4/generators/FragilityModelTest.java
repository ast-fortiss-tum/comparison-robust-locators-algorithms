package de.tum.ls4.generators;

import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static de.tum.ls4.generators.XPathCandidate.ATTRIBUTE_PREFIX;
import static de.tum.ls4.generators.XPathCandidate.LEVEL;
import static de.tum.ls4.generators.XPathCandidate.POSITION;
import static de.tum.ls4.generators.XPathCandidate.TAG;
import static de.tum.ls4.generators.XPathCandidate.TEXT;
import static org.junit.jupiter.api.Assertions.assertEquals;

class FragilityModelTest {

    /** A toolbar whose ids are regenerated in every version (the TinyMCE case of the paper). */
    private static String toolbar(int idBase, String... buttons) {
        StringBuilder sb = new StringBuilder("<html><body><div id='mce_" + idBase + "' class='toolbar'>");
        for (int i = 0; i < buttons.length; i++) {
            sb.append("<button id='mce_").append(idBase + i + 1).append("' class='btn'>")
                    .append(buttons[i]).append("</button>");
        }
        return sb.append("</div></body></html>").toString();
    }

    private static final W3cDom V1 = W3cDom.parse(toolbar(10, "Bold", "Italic"));
    private static final W3cDom V2 = W3cDom.parse(toolbar(20, "Bold", "Italic"));
    private static final W3cDom V3 = W3cDom.parse(toolbar(30, "Underline", "Bold", "Italic"));

    private static FragilityModel learnedOnV1V2() {
        return FragilityModel.empty().learn(List.of(
                new FragilityModel.Mapping(V1.ancestry(V1.find("//button[.='Bold']")), V2.ancestry(V2.find("//button[.='Bold']"))),
                new FragilityModel.Mapping(V1.ancestry(V1.find("//button[.='Italic']")), V2.ancestry(V2.find("//button[.='Italic']")))));
    }

    @Test
    void countsEachSharedAncestorOnce() {
        FragilityModel model = learnedOnV1V2();
        Map<String, FragilityModel.Counter> c = model.counters();
        // nodes: Bold, Italic, div, body, html -> 5 tag/position observations, not 2 x 4 = 8 (+ html twice)
        assertEquals(new FragilityModel.Counter(5, 0), c.get(TAG));
        assertEquals(new FragilityModel.Counter(5, 0), c.get(POSITION));
        // ids of div, Bold and Italic all changed
        assertEquals(new FragilityModel.Counter(0, 3), c.get(ATTRIBUTE_PREFIX + "id"));
        assertEquals(new FragilityModel.Counter(3, 0), c.get(ATTRIBUTE_PREFIX + "class"));
        assertEquals(new FragilityModel.Counter(2, 0), c.get(TEXT));
    }

    @Test
    void weightsFollowThePaper() {
        FragilityModel model = learnedOnV1V2();
        assertEquals(1.0, model.weight(ATTRIBUTE_PREFIX + "id"));
        assertEquals(FragilityModel.ROBUST_WEIGHT, model.weight(TEXT));
        assertEquals(FragilityModel.DEFAULT_UNSEEN_WEIGHT, model.weight(ATTRIBUTE_PREFIX + "aria-label"));
        assertEquals(FragilityModel.DEFAULT_LEVEL_WEIGHT, model.weight(LEVEL));
        assertEquals(0.75, FragilityModel.empty().fragility(List.of(TAG, TEXT)), 1e-12);
    }

    @Test
    void attributesAndTextsMatchAtAnyLevelButTagsAndPositionsAtTheSameLevel() {
        // v2 wraps the link in an extra <span>: tag/position at fixed levels change, attributes and text do not
        W3cDom a = W3cDom.parse("<html><body><div class='nav'><a class='home'>Home</a></div></body></html>");
        W3cDom b = W3cDom.parse("<html><body><div class='nav'><span><a class='home'>Home</a></span></div></body></html>");
        FragilityModel model = FragilityModel.empty().learn(List.of(
                new FragilityModel.Mapping(a.ancestry(a.find("//a")), b.ancestry(b.find("//a")))));
        assertEquals(new FragilityModel.Counter(2, 0), model.counters().get(ATTRIBUTE_PREFIX + "class"));
        assertEquals(new FragilityModel.Counter(1, 0), model.counters().get(TEXT));
        // levels: a/a, div/span (changed), body/div (changed), html/body (changed)
        assertEquals(new FragilityModel.Counter(1, 3), model.counters().get(TAG));
    }

    @Test
    void siderealLearnsToAvoidAutoGeneratedIdsWhereRobulaPlusDoesNot() {
        FragilityModel model = learnedOnV1V2();

        // Generate locators for "Bold" on the current version (v2)
        var bold = V2.find("//button[.='Bold']");
        String robula = new RobulaPlus().generate(V2.ancestry(bold), V2.oracle(bold)).xpath();
        String sidereal = new Sidereal(model).generate(V2.ancestry(bold), V2.oracle(bold)).xpath();
        assertEquals("//*[@id='mce_21']", robula);
        assertEquals("//*[contains(text(),'Bold')]", sidereal);

        // Next version (v3): ids regenerated and a new button inserted before "Bold"
        assertEquals(0, V3.select(robula).getLength(), "ROBULA+ locator breaks");
        assertEquals(1, V3.select(sidereal).getLength(), "SIDEREAL locator survives");
        assertEquals("Bold", V3.select(sidereal).item(0).getTextContent());
    }
}
